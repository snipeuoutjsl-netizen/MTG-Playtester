#!/usr/bin/env python3
"""Compare the Comprehensive Rules (701 keyword actions, 702 keyword abilities) with what app.js mentions.
Usage: pdftotext -layout MagicCompRules.pdf cr.txt && python3 tests/rules-audit.py cr.txt > RULES-COVERAGE.md
A keyword that app.js never names is certainly not handled; one it does name may still be only partly handled."""
import re,sys,os
t=open(sys.argv[1]).read().split('\n'); SRC=os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','src')
app=''.join(open(os.path.join(SRC,f)).read() for f in sorted(os.listdir(SRC)) if f.endswith('.js') and not f.startswith('40-')).lower()   # the generated table itself must not count as a mention
if len(sys.argv)<3:
  for sec,title in (('701','Keyword actions (CR 701)'),('702','Keyword abilities (CR 702)')):
      seen=[]
      for l in t:
          m=re.match(r'^%s\.(\d+)\. (.+)$'%sec,l.strip())
          if m and int(m.group(1))>1 and m.group(2).strip() not in seen: seen.append(m.group(2).strip())
      miss=[n for n in seen if n.lower().split(' (')[0] not in app]
      print('## %s: %d rules, %d never named in app.js\n'%(title,len(seen),len(miss)))
      print(', '.join(miss)+'\n')

if len(sys.argv)>2 and sys.argv[2]=='--table':
    # Writes src/40-rules-table.js: every CR 701/702 rule with a status.  tested = a test in cr-rules.js names that rule number;
    # named = app.js mentions the keyword (needs a test-backed review); none = app.js never mentions it.
    tested=set(re.findall(r"T\('(70[12]\.\d+)",open(os.path.join(os.path.dirname(os.path.abspath(__file__)),'cr-rules.js')).read()))
    rows=[]
    for sec,kind in (('701','action'),('702','ability')):
        seen=set()
        for l in t:
            m=re.match(r'^(%s\.\d+)\. (.+)$'%sec,l.strip())
            if m and not m.group(1).endswith('.1') and m.group(1) not in seen:
                seen.add(m.group(1)); n=m.group(2).strip(); nm=n.lower().split(' (')[0]
                st='tested' if m.group(1) in tested else ('named' if nm in app else 'none')
                rows.append((m.group(1),n,kind,st))
    out=["// GENERATED by tests/rules-audit.py --table from the Comprehensive Rules (do not edit by hand).","// [CR number, name, 'action' | 'ability', status]. status: tested (a rules test names it), named (the app mentions it; needs a test-backed review), none (the app never mentions it).","const RULES_TABLE = ["]
    for r in rows: out.append("  [%s],"%", ".join("'%s'"%x.replace("'","\\'") for x in r))
    out+=["];","const RULES_BY_NAME = new Map(RULES_TABLE.map(r => [r[1].toLowerCase().split(' (')[0], r]));","function crKeyword(name) { return RULES_BY_NAME.get(String(name || '').toLowerCase().trim()) || null; }",""]
    open(os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','src','40-rules-table.js'),'w').write("\n".join(out)); print(len(rows),'rules')
