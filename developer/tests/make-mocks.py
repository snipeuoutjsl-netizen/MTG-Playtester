# Writes mock-cards.json (invented test cards in Scryfall format). Edit the C(...) lines, run: python3 make-mocks.py
import json,re
def cost_cmc(mc):
    n=0
    for s in re.findall(r'\{([^}]+)\}',mc or ''):
        if s.isdigit(): n+=int(s)
        elif s in ('X',): pass
        else: n+=1
    return n
def colors_of(mc):
    return [c for c in 'WUBRG' if '{'+c+'}' in (mc or '') or re.search(r'\{[^}]*'+c+r'[^}]*\}',mc or '')]
cards=[]
def C(name,mc,tl,tx,pt=None,colors=None,**kw):
    o={'object':'card','name':name,'layout':'normal','mana_cost':mc,'cmc':cost_cmc(mc),'type_line':tl,'oracle_text':tx,
       'colors':colors if colors is not None else colors_of(mc),'legalities':{'commander':'legal','modern':'legal','legacy':'legal','vintage':'legal'},'set':'mck','rarity':'common','mock':True}
    o['color_identity']=o['colors']
    if pt: o['power'],o['toughness']=pt.split('/')
    o.update(kw)
    if o.get('card_faces'): o.pop('oracle_text', None); o.pop('power', None); o.pop('toughness', None)   # Scryfall puts a two-faced card's text on its faces
    cards.append(o)
